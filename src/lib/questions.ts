/**
 * 뜻이 겹쳐 로테이션에서 뺀 옛 질문 — 글은 그대로 둔다(옛 답이 이 글 아래 보인다). 짝: 71↔16(요즘 듣는 노래) ·
 * 70↔19(첫인상) · 67·59·48↔30(요즘 설레는 내 모습) · 44↔17(힘들 때 어떻게 해 줄까) · 38↔12(내가 해 준 것) · 64↔34(반한 순간).
 * ⚠ 이미 나온 질문(답이 붙은 번호)의 글은 바꾸지 않는다 — 옛 답이 다른 질문 아래 보인다. 겹치면 여기로 뺀다.
 */
export const RETIRED: readonly number[] = [38, 44, 48, 59, 64, 67, 70, 71];

/**
 * 도는 순서 — 새 질문(75~)을 먼저 한 바퀴(묶음을 번갈아), 그다음 옛 질문. 합쳐서 365개라 1년 동안 안 겹친다.
 * · 첫날은 75 — 옛 번들(번호 순서)도 컷오버 첫날은 75라, 새로 받기 전인 기기와도 첫날은 답이 묶인다.
 * · 묶음은 부드러운 가중 라운드로빈(크기에 비례해 고르게 흩는다) + 어제와 같은 묶음은 건너뛴다.
 * · 옛 질문은 5칸씩 건너 뛰며 섞는다 — 번호 순서면 30~35(스킨십·설렘 팩)가 엿새 연달아 나온다.
 */
export const ORDER: readonly number[] = (() => {
  const groups = THEMES.map(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => a + i));
  for (let i = 365; i < QUESTIONS.length; i++) groups[groups.length - 1].push(i);
  const out: number[] = [groups[0].shift()!];
  const weight = groups.map((g) => g.length);
  const cur = groups.map(() => 0);
  let last = 0;
  for (;;) {
    const live = groups.map((g, i) => (g.length ? i : -1)).filter((i) => i >= 0);
    if (!live.length) break;
    const total = live.reduce((sum, i) => sum + weight[i], 0);
    for (const i of live) cur[i] += weight[i];
    const ranked = [...live].sort((x, y) => cur[y] - cur[x] || x - y);
    const pick = ranked.find((i) => i !== last) ?? ranked[0];
    cur[pick] -= total;
    out.push(groups[pick].shift()!);
    last = pick;
  }
  const retired = new Set(RETIRED);
  const old = Array.from({ length: 75 }, (_, i) => i).filter((i) => !retired.has(i));
  for (let k = 0; k < old.length; k++) out.push(old[(k * 5) % old.length]);
  return out;
})();

/**
 * 로테이션 스케줄 — 질문 풀을 늘릴 때 QUESTIONS.length 를 그대로 쓰면(idx=day%n)
 * 배포 순간 '오늘의 질문'이 모두 바뀌고, 번들 스큐(한쪽 구버전) 시 커플이 서로 다른
 * 질문에 답해 영영 안 묶인다. 그래서 컷오버 일자부터만 새 풀 크기를 적용한다.
 * ⚠ 질문을 추가하면: QUESTIONS 끝에 append + 여기 (내일 이후의 fromDay, 새 순서) 1줄 append.
 *
 * order — 그 컷오버부터 날마다 하나씩 도는 질문 번호 목록(없으면 번호 순서 day % n).
 */
type Phase = { fromDay: number; n: number; order?: readonly number[] };
const ROTATION: Phase[] = [
  { fromDay: 0, n: 30 },
  { fromDay: 20637, n: 36 }, // 2026-07-03 부터 스파이시 팩(31~36번째) 로테이션 편입
  { fromDay: 20638, n: 70 }, // 2026-07-04 부터 확장 팩(37~70번째) 로테이션 편입
  { fromDay: 20639, n: 75 }, // 2026-07-05 부터 추가 팩(71~75번째) 로테이션 편입
  { fromDay: 20722, n: ORDER.length, order: ORDER }, // 2026-09-26 부터 365 — 새 질문을 주제 번갈아 먼저, 겹치는 옛 질문 8개는 뺀다
];

/**
 * 회차 id — 2026-09-26 부터 question_id 에 **날짜**를 붙인다(q12@2026-09-26).
 * 예전엔 답이 질문 번호(q12)에만 묶여서, 같은 질문이 다시 오면 **예전 답이 '이미 쓴 답'으로**
 * 떴다(상대의 예전 답까지 바로 열렸다). 이제 같은 질문이 와도 새 회차라 빈 칸에서 새로 답한다.
 * DB 는 그대로다 — question_id 가 텍스트라 unique(couple_id, question_id, user_id)가 회차마다 따로 걸린다.
 * ⚠ 컷오버는 배포 **다음 날 이후** — 한쪽이 옛 번들이면 같은 날 서로 다른 id 에 답해 안 묶인다.
 */
const INSTANCE_FROM_DAY = 20722;

const pad = (n: number) => String(n).padStart(2, "0");
const dayNumOf = (ref: Date) => Math.floor(Date.UTC(ref.getFullYear(), ref.getMonth(), ref.getDate()) / 86_400_000);

/** 그날의 질문 번호(순수) — 테스트가 회전 규칙을 직접 본다. */
export function questionIndexForDay(dayNum: number): number {
  let ph = ROTATION[0];
  for (const r of ROTATION) if (dayNum >= r.fromDay) ph = r;
  if (ph.order) {
    const m = ph.order.length;
    return ph.order[(((dayNum - ph.fromDay) % m) + m) % m];
  }
  const n = Math.min(ph.n, QUESTIONS.length); // 안전 가드
  return ((dayNum % n) + n) % n;
}

export function todaysQuestion(ref: Date = new Date()): { id: string; text: string; index: number } {
  const dayNum = dayNumOf(ref);
  const idx = questionIndexForDay(dayNum);
  const ymd = `${ref.getFullYear()}-${pad(ref.getMonth() + 1)}-${pad(ref.getDate())}`;
  const id = dayNum >= INSTANCE_FROM_DAY ? `q${idx}@${ymd}` : `q${idx}`;
  return { id, text: QUESTIONS[idx], index: idx };
}

/** question_id('q{idx}' 또는 'q{idx}@YYYY-MM-DD') → 질문 번호. 모르는 모양이면 null. */
export function questionIndex(id: string): number | null {
  const m = /^q(\d+)(?:@\d{4}-\d{2}-\d{2})?$/.exec(id);
  if (!m) return null;
  const idx = Number(m[1]);
  return idx >= 0 && idx < QUESTIONS.length ? idx : null;
}

/** 회차 id 의 날짜(YYYY-MM-DD) — 옛 id('q12')는 날짜가 없어서 null. */
export function questionDate(id: string): string | null {
  return /@(\d{4}-\d{2}-\d{2})$/.exec(id)?.[1] ?? null;
}

/** question_id → 질문 텍스트. */
export function questionText(id: string): string {
  const idx = questionIndex(id);
  return idx == null ? "질문" : QUESTIONS[idx];
}
