// UI 아이콘 34종 — **12×12 도트**. 앱 크롬 전체가 픽셀 톤이 되는 마지막 조각.
//
// 왜 12인가: 본문 폰트 격자가 12(Galmuri11)라 아이콘도 12 격자여야 글자 옆에서 어긋나 보이지
// 않는다. 렌더 크기는 12 의 배수(12/24/36) 로만 쓴다 — 그 사이 값은 도트가 뭉갠다.
//
// 왜 SVG path 로 굽나: 아이콘은 100 곳 넘게, 버튼 안에서 `currentColor` 를 상속해 쓰인다.
// 캔버스로는 색 상속이 안 되고 노드도 무겁다. 도트를 **가로 런으로 합쳐** rect 경로 하나로
// 만들면(보통 12~20 런) 기존 <svg dangerouslySetInnerHTML> 구조를 그대로 쓰면서
// `shape-rendering: crispEdges` 로 도트가 또렷하게 남는다.
//
// ⚠ 저작 규약: 한 줄 = 12칸. '#' 칠함, '.' 빈칸. 길이가 12 가 아니면 rowsToPath 가 즉시 throw.
//   (점을 손으로 세다 틀리면 아트가 통째로 밀린다 — 스프라이트에서 실제로 겪었다.)

/** 12×12 도트 → SVG path d. 가로로 이어진 칸을 한 사각형으로 합친다(노드 수 최소화). */
export function rowsToPath(rows: readonly string[], grid = 12): string {
  if (rows.length !== grid) throw new Error(`icon: 행 수 ${rows.length} ≠ ${grid}`);
  const parts: string[] = [];
  rows.forEach((row, y) => {
    if (row.length !== grid) throw new Error(`icon: ${y}행 길이 ${row.length} ≠ ${grid}`);
    let x = 0;
    while (x < grid) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (x + w < grid && row[x + w] === "#") w++;
      parts.push(`M${x} ${y}h${w}v1h-${w}z`);
      x += w;
    }
  });
  return parts.join("");
}

