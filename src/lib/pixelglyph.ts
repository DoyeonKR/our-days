import { type Palette, type Sprite, ramp } from "./pixel.ts";
import { PIXEL_PAL } from "./pixelpal.ts";

export const mkRow = (w: number) => (...rs: readonly (readonly [number, string])[]): string => {
  const a = new Array<string>(w).fill(".");
  for (const [x0, s] of rs) {
    for (let i = 0; i < s.length; i++) {
      const x = x0 + i;
      if (x < 0 || x >= w) throw new Error(`ui row: x=${x} 범위 밖 ("${s}")`);
      a[x] = s[i];
    }
  }
  return a.join("");
};
export const r24 = mkRow(24);
export const r16 = mkRow(16);
export const r12 = mkRow(12);

/** UI 팔레트 — 주색(o/H/m/M/d/D) · 보조색(p/h/n/N/k/K) + 고정 강조색. */
export function uiPal(main: readonly string[], sub: readonly string[]): Palette {
  const M = ramp(main);
  const N = ramp(sub);
  return {
    o: M.o, H: M.H, m: M.b, M: M.B, d: M.d, D: M.D,
    p: N.o, h: N.H, n: N.b, N: N.B, k: N.d, K: N.D,
    y: PIXEL_PAL.gold[1], Y: PIXEL_PAL.gold[2], s: "#fff3b0", w: "#fffdf7",
    r: "#ff5a5a", R: "#c2323f", g: "#6fcf5a", G: "#2f8a3a", c: "#7fd8f0", C: "#2b87b3", e: "#2b2f3d",
    b: "#ff9ec0", // 볼터치 · 혀 · 코 — 기분 도트(얼굴·동물)
  };
}
export const sprite = (w: number, rows: string[], pal: Palette): Sprite => ({ w, h: rows.length, pal, rows });

